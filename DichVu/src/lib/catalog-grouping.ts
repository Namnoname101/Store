export function normalizeThumbnailUrl(url?: string | null): string {
  if (!url || !url.trim()) return "";
  const trimmed = url.trim();

  // 1. Google Drive temporary web viewer format (drive-viewer/AKGpih...)
  // These are ephemeral session tokens generated by Google Drive web viewer that expire in 1-2 hours and return 403 Forbidden.
  // They are invalid as permanent thumbnail URLs.
  if (trimmed.includes("drive-viewer")) {
    return "";
  }

  // 2. Standard Google Drive file/d/ or open?id= or uc?id= format
  const gDriveMatch = trimmed.match(
    /(?:lh3\.google\.com(?:\/u\/\d+)?\/d\/|drive\.google\.com\/(?:file\/d\/|open\?id=|uc\?(?:[^&]+&)*id=))([a-zA-Z0-9_-]+)/i
  );
  if (gDriveMatch && gDriveMatch[1]) {
    return `https://lh3.googleusercontent.com/d/${gDriveMatch[1]}`;
  }

  return trimmed;
}

